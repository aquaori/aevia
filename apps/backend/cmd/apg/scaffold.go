package main

import (
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"collaborative-whiteboard/apps/backend/internal/apg"
)

// scaffoldScopePermissions keeps the generated example inside its own governance
// boundary: a user plugin may read the scene, a system plugin may also write it.
func scaffoldScopePermissions(scope string) []string {
	if scope == "system" {
		return []string{"scene.read", "scene.write", "ui.preview"}
	}
	return []string{"scene.read", "ui.preview"}
}

func scaffoldMainJS(scope string) string {
	mutate := ""
	if scope == "system" {
		mutate = `
  // System plugins may also produce native operations (one shared history group):
  // apg.mutate({ kind: "shape.create", shape: "rectangle", start: [0.4, 0.4], end: [0.6, 0.6], color: "#2563EB" });
`
	}
	return `// Guest entry point. It runs inside the QuickJS sandbox: no DOM, network or host objects.
apg.registerCommand("run", function () {
  const scene = apg.readScene();
  const items = scene && Array.isArray(scene.items) ? scene.items : [];
  const elements = new Set(items.map((item) => item.elementId));
  apg.preview("Elements: " + elements.size);
` + mutate + `});
`
}

const scaffoldReadme = `# Plugin scaffold

Generated by "apg init". Edit manifest.json and main.js, then:

    apg pack manifest.json ../my-plugin.apg
    apg validate ../my-plugin.apg

Executable plugins are opt-in for the deployment: signing, installing and enabling a
package is a deployer action, not a user action. See docs/apg/development.md.
`

func scaffoldManifest(id, scope string) ([]byte, error) {
	name := "Scaffold Plugin"
	if index := strings.LastIndex(id, "."); index >= 0 && index < len(id)-1 {
		tail := id[index+1:]
		name = strings.ToUpper(tail[:1]) + tail[1:]
	}
	permissions := scaffoldScopePermissions(scope)
	quoted := make([]string, 0, len(permissions))
	for _, permission := range permissions {
		quoted = append(quoted, fmt.Sprintf("%q", permission))
	}
	manifest := fmt.Sprintf(`{
  "manifestVersion": 2,
  "apiVersion": 1,
  "id": %q,
  "name": %q,
  "version": "0.1.0",
  "scope": %q,
  "permissions": [%s],
  "main": "main.js",
  "contributes": {
    "commands": [
      { "id": "run", "label": "Run Plugin" }
    ]
  }
}
`, id, name, scope, strings.Join(quoted, ", "))
	if _, err := apg.ValidateManifestJSON([]byte(manifest)); err != nil {
		return nil, err
	}
	return []byte(manifest), nil
}

func initPlugin(dir, id, scope string) error {
	if scope != "user" && scope != "system" {
		return errors.New("usage: apg init <plugin-dir> <plugin-id> [user|system]")
	}
	manifest, err := scaffoldManifest(id, scope)
	if err != nil {
		return err
	}
	entries, err := os.ReadDir(dir)
	if err == nil && len(entries) > 0 {
		return fmt.Errorf("refusing to scaffold into non-empty directory %s", dir)
	}
	if err != nil && !errors.Is(err, os.ErrNotExist) {
		return err
	}
	if err := os.MkdirAll(dir, 0755); err != nil {
		return err
	}
	files := []struct {
		name string
		body []byte
	}{
		{"manifest.json", manifest},
		{"main.js", []byte(scaffoldMainJS(scope))},
		{"README.md", []byte(scaffoldReadme)},
	}
	for _, file := range files {
		target := filepath.Join(dir, file.name)
		handle, err := os.OpenFile(target, os.O_CREATE|os.O_EXCL|os.O_WRONLY, 0644)
		if err != nil {
			return err
		}
		_, writeErr := handle.Write(file.body)
		closeErr := handle.Close()
		if writeErr != nil {
			return writeErr
		}
		if closeErr != nil {
			return closeErr
		}
	}
	return nil
}
